#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const outputPath = path.resolve(repoRoot, 'src', 'generated', 'openapi-operations.generated.ts');
const localFallbackPath =
  process.env.OPENAPI_LOCAL_PATH ??
  path.resolve(repoRoot, '..', 'openapi', 'openapi', 'openapi.spec3.yaml');
const remoteSpecUrl =
  process.env.OPENAPI_SPEC_URL ??
  'https://openapi.frontal.dev/openapi.spec3.yaml';
const strictRemote = process.env.OPENAPI_SPEC_STRICT === '1';

const HTTP_METHODS = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);

function normalizePath(p) {
  if (!p) return '/';
  if (p.length > 1 && p.endsWith('/')) return p.slice(0, -1);
  return p;
}

async function readRemoteSpec(url) {
  const response = await fetch(url, {
    headers: { Accept: 'application/yaml, text/yaml, text/plain, */*' },
  });

  if (!response.ok) {
    throw new Error(`HTTP ${response.status}`);
  }

  return response.text();
}

async function readSpecSource() {
  try {
    const text = await readRemoteSpec(remoteSpecUrl);
    console.log(`Using remote OpenAPI source: ${remoteSpecUrl}`);
    return text;
  } catch (error) {
    if (strictRemote) {
      throw new Error(
        `Failed to fetch remote OpenAPI spec (${remoteSpecUrl}): ${String(error)}`
      );
    }

    if (!fs.existsSync(localFallbackPath)) {
      throw new Error(
        `Remote spec unavailable (${remoteSpecUrl}) and local fallback not found (${localFallbackPath}).`
      );
    }

    console.warn(
      `Remote spec unavailable (${remoteSpecUrl}). Falling back to local spec: ${localFallbackPath}`
    );
    return fs.readFileSync(localFallbackPath, 'utf8');
  }
}

const specRaw = await readSpecSource();
const spec = YAML.parse(specRaw);
const paths = spec.paths ?? {};

const operations = [];
for (const [routePath, entry] of Object.entries(paths)) {
  for (const [method, value] of Object.entries(entry ?? {})) {
    if (!HTTP_METHODS.has(method)) continue;
    const operationId = value?.operationId ?? null;
    operations.push({
      key: `${method.toUpperCase()} ${normalizePath(routePath)}`,
      method: method.toUpperCase(),
      path: normalizePath(routePath),
      operationId,
    });
  }
}

operations.sort((a, b) => a.key.localeCompare(b.key));

const out = `/* eslint-disable */\n// AUTO-GENERATED by scripts/generate-openapi-operations.mjs\n// Do not edit by hand.\n\nexport type OpenApiOperation = {\n  key: string;\n  method: string;\n  path: string;\n  operationId: string | null;\n};\n\nexport const OPENAPI_OPERATIONS: OpenApiOperation[] = ${JSON.stringify(operations, null, 2)};\n\nexport const OPENAPI_OPERATION_KEYS = new Set(OPENAPI_OPERATIONS.map((op) => op.key));\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, out, 'utf8');

console.log(`Generated ${operations.length} operations at ${outputPath}`);
