#!/usr/bin/env bash
set -euo pipefail

. "$(dirname "$0")/bootstrap.sh"

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

# Download the artifacts produced by the "build" step (skipped locally).
if command -v buildkite-agent >/dev/null 2>&1; then
  echo "--- :arrow_down: Downloading build artifacts"
  buildkite-agent artifact download "dist/index.js" .
  buildkite-agent artifact download "dist/cli" .
else
  echo "--- :hammer: Running locally: using dist/ from a local build"
fi

chmod +x dist/index.js dist/cli

echo "--- :rocket: Smoke test the built CLI"
./dist/index.js --version
./dist/index.js --help

# Mirror of the integration-test job in .github/workflows/ci.yml:
# fresh project → types → local dev server → deploy dry-run.
WORK_DIR="$(mktemp -d)"
export FRONTAL_CONFIG_DIR="${WORK_DIR}/frontal-config"

cd "${WORK_DIR}"
"${REPO_ROOT}/dist/cli" init --name demo
cd demo
"${REPO_ROOT}/dist/cli" types
test -f src/frontal-configuration.d.ts
head -1 src/frontal-configuration.d.ts | grep -q "Generated by frontal types"

"${REPO_ROOT}/dist/cli" dev --port 8787 --no-watch > dev.log 2>&1 &
DEV_PID=$!
sleep 5
curl -sf localhost:8787/health | grep -q '"ok":true'
curl -sf -X POST localhost:8787/v1/agents -H 'content-type: application/json' -d '{"name":"ci"}' | grep -q '"id":"agt_'
printf 'export default { fetch: () => new Response("ci") };\n' > src/index.ts
"${REPO_ROOT}/dist/cli" deploy --dry-run --outdir out
test -f out/index.js && test -f out/manifest.json
kill -INT "${DEV_PID}" 2>/dev/null || true
cat dev.log

cd "${REPO_ROOT}"

echo "--- :book: README examples"
bun scripts/run-readme-blocks.ts
