import { existsSync, readFileSync } from "node:fs";
import { dirname, relative, sep } from "node:path";
import { CliError } from "@/errors/cli-error.js";
import { EXIT_CODES } from "@/errors/exit-codes.js";
import { GENERATED_BANNER, ONTOLOGY_FILES } from "@/lib/ontology/constants.js";
import { ONTOLOGY_ERROR_CODES } from "@/lib/ontology/errors.js";
import type { RenderMeta } from "@/lib/ontology/render/header.js";
import { renderTypesReference } from "@/lib/ontology/render/reference.js";
import type { WriteOutcome, Writer } from "@/lib/ontology/write.js";

/** Where the reference file goes and how it names `ontology.d.ts`. */
export interface TypesReference {
  /** Project-relative path for messages, with forward slashes. */
  displayPath: string;
  /** Absolute path of the reference file. */
  file: string;
  /** Path from the reference file to `ontology.d.ts`, with forward slashes. */
  typesPath: string;
}

const LEADING_DOT_SLASH = /^\.\//;

/** Forward-slash relative path, prefixed with `./` when it stays in the same folder. */
function posixRelative(from: string, to: string): string {
  const rel = relative(from, to).split(sep).join("/");
  return rel.startsWith(".") ? rel : `./${rel}`;
}

/** Builds the reference descriptor for a file under the project root. */
export function referenceFor(
  file: string,
  projectRoot: string,
  frontalDir: string
): TypesReference {
  return {
    displayPath: posixRelative(projectRoot, file).replace(
      LEADING_DOT_SLASH,
      ""
    ),
    file,
    typesPath: posixRelative(
      dirname(file),
      `${frontalDir}${sep}${ONTOLOGY_FILES.types}`
    ),
  };
}

/** Expected bytes of the reference file for the given ontology snapshot. */
export function referenceContent(
  reference: TypesReference,
  meta: RenderMeta
): string {
  return renderTypesReference(reference.typesPath, meta);
}

/**
 * Refuses to touch an existing file that frontal did not generate. Called
 * before any write, so a refusal leaves `.frontal/` untouched.
 */
export function assertReferenceWritable(reference: TypesReference): void {
  if (!existsSync(reference.file)) {
    return;
  }
  const existing = readFileSync(reference.file, "utf-8");
  if (existing.includes(GENERATED_BANNER)) {
    return;
  }
  throw new CliError(
    ONTOLOGY_ERROR_CODES.referenceNotOwned,
    `${reference.displayPath} exists and was not generated by frontal sync.`,
    {
      exitCode: EXIT_CODES.CONFIG_ERROR,
      fix: "Choose another file with --types-out <file>, or move the existing file aside and run frontal sync again.",
    }
  );
}

/** Writes the reference file atomically after checking that it is ours. */
export function writeReference(
  reference: TypesReference,
  content: string,
  write: Writer
): WriteOutcome {
  assertReferenceWritable(reference);
  return write(reference.file, content);
}
