import {
  type FieldType,
  type NormalizedEntity,
  type NormalizedField,
  type NormalizedOntology,
  pascalCase,
  propertyKey,
} from "@/lib/ontology/model.js";

/** Contract version written to version.json. Bump when generated output changes shape. */
export const CONTRACT_VERSION = 1;
/**
 * SDK versions that understand the generated client (createFrontalClient with
 * a type argument and runtime metadata).
 * ASSUMPTION: the first SDK release with that factory is 2.x; update when known.
 */
export const SDK_RANGE = ">=2.0.0 <3.0.0";

export interface GenerateInput {
  generatorVersion: string;
  schemaHash: string;
}

export interface GeneratedFiles {
  /** Generated typed factory (`client.ts`). */
  clientTs: string;
  /** Generated ontology declarations (`ontology.d.ts`). */
  ontologyDts: string;
  /** Hashes and versions (`version.json`). No timestamps. */
  versionJson: string;
}

const PRIMITIVE_TYPES: Record<FieldType, string> = {
  array: "unknown",
  boolean: "boolean",
  currency: "number",
  enum: "string",
  float: "number",
  integer: "number",
  json: "unknown",
  string: "string",
  text: "string",
  // ASSUMPTION: timestamps travel as ISO 8601 strings over JSON, not Date.
  timestamp: "string",
  uuid: "string",
  vector: "number[]",
};

const ITEM_TYPES: Record<string, string> = {
  boolean: "boolean",
  currency: "number",
  float: "number",
  integer: "number",
  string: "string",
  text: "string",
  timestamp: "string",
  uuid: "string",
};

function enumAliasFor(entity: string, field: string): string {
  return `${pascalCase(entity)}${pascalCase(field)}`;
}

function valueTypeOf(entity: string, field: NormalizedField): string {
  if (field.type === "enum") {
    return enumAliasFor(entity, field.name);
  }
  if (field.type === "array") {
    return `${ITEM_TYPES[field.items ?? ""] ?? "unknown"}[]`;
  }
  return PRIMITIVE_TYPES[field.type];
}

function literalUnion(values: string[]): string {
  return values.map((value) => JSON.stringify(value)).join(" | ");
}

function member(key: string, type: string, optional: boolean): string {
  return `${key}${optional ? "?" : ""}: ${type};`;
}

/** Renders `{ ... }` with the given members, or `Record<string, never>` when empty. */
function objectType(members: string[], indent: string): string {
  if (members.length === 0) {
    return "Record<string, never>";
  }
  const inner = members.map((line) => `${indent}  ${line}`).join("\n");
  return `{\n${inner}\n${indent}}`;
}

function renderEntity(entity: NormalizedEntity): string {
  const read: string[] = [member("id", "string", false)];
  const create: string[] = [];
  const update: string[] = [];

  for (const field of entity.fields) {
    const key = propertyKey(field.name);
    const base = valueTypeOf(entity.name, field);
    const nullable = field.required ? base : `${base} | null`;

    // Read: a required field is always present; an optional one may be null or absent.
    read.push(
      field.required ? member(key, base, false) : member(key, nullable, true)
    );

    if (field.readOnly) {
      continue;
    }
    if (field.required && !field.hasDefault) {
      create.push(member(key, base, false));
    } else if (field.required) {
      create.push(member(key, base, true));
    } else {
      create.push(member(key, nullable, true));
    }
    update.push(member(key, nullable, true));
  }

  // Relations: lazy accessors, emitted as data here and typed in the SDK.
  const relations = entity.relations.map((relation) =>
    member(
      propertyKey(relation.name),
      `{ target: ${JSON.stringify(relation.target)}; optional: ${relation.optional} }`,
      false
    )
  );

  const body = [
    `read: ${objectType(read, "    ")};`,
    `create: ${objectType(create, "    ")};`,
    `update: ${objectType(update, "    ")};`,
    // `{}` (not Record<string, never>) so keyof yields no relation names.
    `relations: ${relations.length === 0 ? "Record<never, never>" : objectType(relations, "    ")};`,
  ];
  return `  ${propertyKey(entity.name)}: {\n${body
    .map((line) => `    ${line}`)
    .join("\n")}\n  };`;
}

function renderHeader(input: GenerateInput): string {
  return [
    "// AUTO-GENERATED BY FRONTAL CLI. DO NOT EDIT MANUALLY.",
    `// Ontology hash: ${input.schemaHash}`,
    `// Generator version: ${input.generatorVersion}`,
  ].join("\n");
}

function renderEnums(entities: NormalizedEntity[]): string[] {
  const blocks: string[] = [];
  for (const entity of entities) {
    for (const field of entity.fields) {
      if (field.type === "enum" && field.enumValues) {
        blocks.push(
          `export type ${enumAliasFor(entity.name, field.name)} = ${literalUnion(field.enumValues)};`
        );
      }
    }
  }
  return blocks;
}

/** Renders `ontology.d.ts`. Deterministic: same input, same bytes. */
export function renderOntologyDts(
  model: NormalizedOntology,
  input: GenerateInput
): string {
  const enums = renderEnums(model.entities);
  const lines = [renderHeader(input), ""];
  for (const declaration of enums) {
    lines.push(declaration);
  }
  if (enums.length > 0) {
    lines.push("");
  }
  if (model.entities.length === 0) {
    lines.push("export type Ontology = Record<never, never>;");
  } else {
    lines.push("export interface Ontology {");
    for (const entity of model.entities) {
      lines.push(renderEntity(entity));
    }
    lines.push("}");
  }
  return `${lines.join("\n")}\n`;
}

/** Renders `client.ts`, the typed factory that imports the generated ontology. */
export function renderClientTs(
  model: NormalizedOntology,
  input: GenerateInput
): string {
  const entityNames = model.entities.map((entity) => entity.name);
  const relationEntries = model.entities.flatMap((entity) => {
    if (entity.relations.length === 0) {
      return [];
    }
    const rels = entity.relations.map(
      (relation) =>
        `      ${propertyKey(relation.name)}: { foreignKey: ${JSON.stringify(relation.foreignKey)}, target: ${JSON.stringify(relation.target)} },`
    );
    return [`    ${propertyKey(entity.name)}: {\n${rels.join("\n")}\n    },`];
  });
  const relations =
    relationEntries.length === 0
      ? "{}"
      : `{\n${relationEntries.join("\n")}\n  }`;
  const entities =
    entityNames.length === 0
      ? "[]"
      : `[\n${entityNames.map((name) => `    ${JSON.stringify(name)},`).join("\n")}\n  ]`;

  return `${renderHeader(input)}
import { createFrontalClient, type SdkConfig } from "@frontal-labs/sdk";
import type { Ontology } from "./ontology";

const runtime = {
  entities: ${entities},
  relations: ${relations},
} as const;

export function createFrontal(config: SdkConfig) {
  return createFrontalClient<Ontology>(config, runtime);
}
`;
}

/** Renders `version.json`. Keys are sorted; there are no timestamps. */
export function renderVersionJson(
  model: NormalizedOntology,
  input: GenerateInput
): string {
  const entities: Record<string, number | null> = {};
  for (const entity of model.entities) {
    entities[entity.name] = entity.version;
  }
  return `${JSON.stringify(
    {
      contractVersion: CONTRACT_VERSION,
      entities,
      generatorVersion: input.generatorVersion,
      schemaHash: input.schemaHash,
      sdkRange: SDK_RANGE,
    },
    null,
    2
  )}\n`;
}

/** Generates all three declaration files from a normalized ontology. */
export function generateFiles(
  model: NormalizedOntology,
  input: GenerateInput
): GeneratedFiles {
  return {
    clientTs: renderClientTs(model, input),
    ontologyDts: renderOntologyDts(model, input),
    versionJson: renderVersionJson(model, input),
  };
}
